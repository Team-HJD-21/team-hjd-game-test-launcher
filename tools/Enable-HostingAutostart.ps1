#requires -Version 7.5
[CmdletBinding()]
param(
    [ValidateSet('Enable','Disable','Status')][string]$Action='Enable',
    [string]$PrivateRoot=(Join-Path (Split-Path $PSScriptRoot) '.local/production-distribution'),
    [string]$PythonPath,
    [string]$CloudflaredPath=(Join-Path (Split-Path $PSScriptRoot) '.deps/cloudflared/2026.10.5/cloudflared.exe'),
    [string]$TokenFile,
    [ValidatePattern('^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$')][string]$TunnelId='888292a7-043a-468f-bba1-4b914592bfff',
    [ValidateRange(1024,65535)][int]$Port=8443,
    [switch]$ValidateOnly
)
$ErrorActionPreference='Stop'
. (Join-Path $PSScriptRoot 'HostingCommon.ps1')
if(-not $IsWindows){throw 'Per-user hosting autostart is supported on Windows.'}
$root=[IO.Path]::GetFullPath($PrivateRoot);Assert-HostingPath $root
$script=Join-Path $PSScriptRoot 'Start-PlaytestHosting.ps1'
$pwsh=(Get-Process -Id $PID).Path
$keyPath='Software\Microsoft\Windows\CurrentVersion\Run'
$valueName='TeamHJDPlaytestHosting'
$wrapper=Join-Path $root 'hosting-autostart.ps1';Assert-HostingPath $wrapper
$arguments=@('-NoLogo','-NoProfile','-WindowStyle','Hidden','-File',(Quote-HostingArgument $wrapper))
$command=(Quote-HostingArgument $pwsh)+' '+($arguments -join ' ')
if($command.Length -gt 259){throw 'Windows Run value exceeds its 260-character limit. Use a shorter private root path or a per-user scheduled task.'}
$launch=@{PrivateRoot=$root;CloudflaredPath=[IO.Path]::GetFullPath($CloudflaredPath);TunnelId=$TunnelId;Port=$Port}
if($TokenFile){$launch.TokenFile=[IO.Path]::GetFullPath($TokenFile)};if($PythonPath){$launch.PythonPath=[IO.Path]::GetFullPath($PythonPath)}
if($Action -eq 'Enable'){
    $null=& $script @launch -ValidateOnly
}
$result=[ordered]@{Action=$Action;RegistryKey='HKCU\'+$keyPath;RegistryName=$valueName;Enabled=$null;RegisteredForThisRoot=$null;Command=$command;WrapperPath=$wrapper;LaunchParameters=$launch;Trigger='Current Windows user logon';PrivateRoot=$root;RequiresAdministrator=$false;ValidationOnly=[bool]$ValidateOnly}
if($ValidateOnly){return [pscustomobject]$result}
$key=[Microsoft.Win32.Registry]::CurrentUser.OpenSubKey($keyPath,$false)
try{$existing=if($key){$key.GetValue($valueName,$null,[Microsoft.Win32.RegistryValueOptions]::DoNotExpandEnvironmentNames)}else{$null}}finally{if($key){$key.Dispose()}}
$result.Enabled=($null -ne $existing)
$result.RegisteredForThisRoot=($existing -and ([string]$existing).Contains((Quote-HostingArgument $wrapper),[StringComparison]::OrdinalIgnoreCase))
if($Action -eq 'Status'){return [pscustomobject]$result}
if($existing -and -not ([string]$existing).Contains((Quote-HostingArgument $wrapper),[StringComparison]::OrdinalIgnoreCase)){throw 'The autostart value belongs to a different private root; preserved without changes.'}
if($Action -eq 'Enable'){
    # A short private wrapper keeps the Run command within Windows' length bound.
    $lines=@("# Generated by TeamHJD Enable-HostingAutostart.ps1; no credentials are embedded.","`$ErrorActionPreference='Stop'","`$parameters=@{")
    foreach($entry in $launch.GetEnumerator()){$lines+=('    '+$entry.Key+"='"+([string]$entry.Value).Replace("'","''")+"'")}
    $lines+=@('}',("& '"+$script.Replace("'","''")+"' @parameters"))
    $temporary=$wrapper+'.'+[Guid]::NewGuid().ToString('N')+'.tmp'
    try{[IO.File]::WriteAllLines($temporary,$lines,[Text.UTF8Encoding]::new($false));[IO.File]::Move($temporary,$wrapper,$true)}finally{if([IO.File]::Exists($temporary)){[IO.File]::Delete($temporary)}}
}
$writable=[Microsoft.Win32.Registry]::CurrentUser.CreateSubKey($keyPath,$true)
try{
    if($Action -eq 'Enable'){$writable.SetValue($valueName,$command,[Microsoft.Win32.RegistryValueKind]::String);$result.Enabled=$true;$result.RegisteredForThisRoot=$true}
    else{$writable.DeleteValue($valueName,$false);$result.Enabled=$false;$result.RegisteredForThisRoot=$false}
}finally{$writable.Dispose()}
[pscustomobject]$result
